#ifndef SLD_MATH_TYPES_HPP
#define SLD_MATH_TYPES_HPP

#include <sld.hpp>

#define SLD_MATH_API inline

namespace sld {

    //--------------------------------------------------------------------
    // VECTOR 2D 
    //--------------------------------------------------------------------

    struct vec2 {
        union {
            f32 v[2];
            struct {
                f32 x;
                f32 y;
            };
        };
    };

    //--------------------------------------------------------------------
    // VECTOR 3D 
    //--------------------------------------------------------------------

    struct vec3 {
        union {
            f32 v[3];
            struct {
                f32 x;
                f32 y;
                f32 z;
            };
        };
    };

    //--------------------------------------------------------------------
    // VECTOR 4D 
    //--------------------------------------------------------------------

    struct vec4 {
        union {
            f32 v[4];
            struct {
                f32 x;
                f32 y;
                f32 z;
                f32 w;
            };
        };
    };

    //--------------------------------------------------------------------
    // PLANE
    //--------------------------------------------------------------------

    // the points p where dot(normal, p) == distance
    // with a unit normal, distance is how far the plane is from the origin along the normal
    struct plane {
        vec3 normal;
        f32  distance;
    };

    //--------------------------------------------------------------------
    // RAY
    //--------------------------------------------------------------------

    // the points origin + (direction * t), for t >= 0
    struct ray {
        vec3 origin;
        vec3 direction;
    };

    //--------------------------------------------------------------------
    // QUATERNION
    //--------------------------------------------------------------------

    struct quat {
        union {
            f32 q[4];
            struct {
                f32 x;
                f32 y;
                f32 z;
                f32 w;
            };
        };
    };

    //--------------------------------------------------------------------
    // MATRIX 3X3 
    //--------------------------------------------------------------------

    struct mat3 {
        union {
            f32 m[9];
            struct {
                f32 r0c0;
                f32 r0c1;
                f32 r0c2;
                f32 r1c0;
                f32 r1c1;
                f32 r1c2;
                f32 r2c0;
                f32 r2c1;
                f32 r2c2;
            };
            struct {
                vec3 r0;
                vec3 r1;
                vec3 r2;
            };
        };
    };

    //--------------------------------------------------------------------
    // MATRIX 4X4 
    //--------------------------------------------------------------------
    
    struct mat4 {
        union {
            f32 m[16];
            struct {
                f32 r0c0;
                f32 r0c1;
                f32 r0c2;
                f32 r0c3;
                f32 r1c0;
                f32 r1c1;
                f32 r1c2;
                f32 r1c3;
                f32 r2c0;
                f32 r2c1;
                f32 r2c2;
                f32 r2c3;
                f32 r3c0;
                f32 r3c1;
                f32 r3c2;
                f32 r3c3;
            };
            struct {
                vec4 r0;
                vec4 r1;
                vec4 r2;
                vec4 r3;
            };
        };
    };

};

#endif //SLD_MATH_TYPES_HPP